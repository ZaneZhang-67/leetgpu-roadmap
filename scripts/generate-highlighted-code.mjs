import { readFile, writeFile } from "node:fs/promises"
import { codeToHtml } from "shiki"

const sourcePath = new URL("../src/data/code-samples.js", import.meta.url)
const outputPath = new URL("../src/generated/highlighted-code.js", import.meta.url)
const { codeSamples } = await import(sourcePath.href + `?t=${Date.now()}`)

function escapeAttribute(value) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
}

const entries = []

for (const [id, sample] of Object.entries(codeSamples)) {
  const highlighted = await codeToHtml(sample.code, {
    lang: sample.language,
    themes: {
      light: "light-plus",
      dark: "dark-plus",
    },
    defaultColor: false,
    transformers: [
      ...(sample.plain ? [{
        pre(node) {
          this.addClassToHast(node, "plain-code")
        },
      }] : []),
      ...(sample.lineNumbers
      ? [{
          pre(node) {
            this.addClassToHast(node, "has-line-numbers")
          },
          line(node, line) {
            node.properties["data-line"] = line
          },
        }]
      : []),
    ],
  })

  const html = `<div class="code-block" data-code-id="${escapeAttribute(id)}">
  <div class="code-block-header">
    <span class="code-file">${escapeAttribute(sample.fileName)}</span>
    <span class="code-language">${escapeAttribute(sample.label)}</span>
    <button class="copy-code-button" type="button" data-copy-code="${escapeAttribute(id)}" aria-label="复制 ${escapeAttribute(sample.fileName)}">复制</button>
  </div>
  <div class="code-block-body">${highlighted}</div>
</div>`

  entries.push(`  ${JSON.stringify(id)}: ${JSON.stringify(html)}`)
}

const output = `// This file is generated by scripts/generate-highlighted-code.mjs
export const highlightedCode = {\n${entries.join(",\n")}\n}\n`
await writeFile(outputPath, output, "utf8")

const generated = await readFile(outputPath, "utf8")
console.log(`Generated ${Object.keys(codeSamples).length} highlighted code blocks (${generated.length} bytes)`)
